    /// <summary>Segni degli accenti: righe di 8 caratteri da sovrapporre al glifo base.</summary>
    private static readonly string[] GraveRows = ["..#.....", "...#...."];

    private static readonly string[] AcuteRows = ["....#...", "...#...."];

    /// <summary>
    /// Accenti composti sul glifo base: carattere risultante, carattere base, righe dell'accento e riga di partenza.
    /// Maiuscole: accento nelle righe 0..1. Minuscole: righe 3..4. La i minuscola usa le righe 2..3 (sopra il punto).
    /// </summary>
    private static readonly (char Target, char Source, string[] Rows, int FirstRow)[] Accents =
    [
        ('À', 'A', GraveRows, 0),
        ('È', 'E', GraveRows, 0),
        ('É', 'E', AcuteRows, 0),
        ('Ì', 'I', GraveRows, 0),
        ('Ò', 'O', GraveRows, 0),
        ('Ù', 'U', GraveRows, 0),
        ('à', 'a', GraveRows, 3),
        ('è', 'e', GraveRows, 3),
        ('é', 'e', AcuteRows, 3),
        ('ì', 'i', GraveRows, 2),
        ('ò', 'o', GraveRows, 3),
        ('ù', 'u', GraveRows, 3),
    ];

    private static readonly Dictionary<char, byte[]> Glyphs = BuildGlyphs();

    /// <summary>Indica se il carattere ha un glifo proprio (altrimenti si disegna <see cref="Fallback"/>).</summary>
    /// <param name="c">Carattere da verificare.</param>
    public static bool IsSupported(char c) => Glyphs.ContainsKey(c);

    /// <summary>
    /// Restituisce le 16 righe del glifo: byte i = riga i, bit 7 = colonna 0. Caratteri non supportati
    /// restituiscono il glifo di <see cref="Fallback"/>.
    /// </summary>
    /// <param name="c">Carattere da disegnare.</param>
    public static ReadOnlySpan<byte> GetGlyph(char c)
    {
        return Glyphs.TryGetValue(c, out byte[]? glyph) ? glyph : Glyphs[Fallback];
    }

    /// <summary>Restituisce se il pixel (x, y) del glifo e' acceso. x in 0..7 (sinistra-destra), y in 0..15 (alto-basso).</summary>
    /// <param name="c">Carattere da leggere.</param>
    /// <param name="x">Colonna, da 0 a <see cref="GlyphWidth"/> - 1.</param>
    /// <param name="y">Riga, da 0 a <see cref="GlyphHeight"/> - 1.</param>
    public static bool GetPixel(char c, int x, int y)
    {
        if ((uint)x >= GlyphWidth)
        {
            throw new ArgumentOutOfRangeException(nameof(x), "La colonna del glifo deve essere tra 0 e 7.");
        }

        if ((uint)y >= GlyphHeight)
        {
            throw new ArgumentOutOfRangeException(nameof(y), "La riga del glifo deve essere tra 0 e 15.");
        }

        return (GetGlyph(c)[y] & (0x80 >> x)) != 0;
    }

    private static Dictionary<char, byte[]> BuildGlyphs()
    {
        var map = new Dictionary<char, byte[]>(Art.Count + Accents.Length);
        foreach (KeyValuePair<char, string> entry in Art)
        {
            map[entry.Key] = ParseGlyph(entry.Key, entry.Value);
        }

        foreach (var (target, source, rows, firstRow) in Accents)
        {
            byte[] glyph = (byte[])map[source].Clone();
            for (int i = 0; i < rows.Length; i++)
            {
                glyph[firstRow + i] |= RowBits(rows[i]);
            }

            map[target] = glyph;
        }

        return map;
    }

    private static byte[] ParseGlyph(char symbol, string art)
    {
        string[] lines = art.Split('\n', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries);
        if (lines.Length != GlyphHeight)
        {
            throw new InvalidOperationException($"Il glifo '{symbol}' ha {lines.Length} righe invece di {GlyphHeight}.");
        }

        var rows = new byte[GlyphHeight];
        for (int y = 0; y < GlyphHeight; y++)
        {
            rows[y] = RowBits(lines[y]);
        }

        return rows;
    }

    private static byte RowBits(string row)
    {
        if (row.Length != GlyphWidth)
        {
            throw new InvalidOperationException($"Riga di glifo di {row.Length} caratteri invece di {GlyphWidth}: '{row}'.");
        }

        byte bits = 0;
        for (int x = 0; x < GlyphWidth; x++)
        {
            char ch = row[x];
            if (ch == '#')
            {
                bits |= (byte)(0x80 >> x);
            }
            else if (ch != '.')
            {
                throw new InvalidOperationException($"Carattere non valido nel glifo: '{ch}'.");
            }
        }

        return bits;
    }
